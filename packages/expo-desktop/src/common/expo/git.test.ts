import spawnAsync from "@expo/spawn-async";
import prompts from "prompts";
import { afterEach, beforeEach, expect, test, vi } from "vitest";

import packageJSON from "../../../package.json" with { type: "json" };
import { initGitRepoAsync } from "./git.ts";

vi.mock("@expo/spawn-async", () => ({ default: vi.fn() }));
vi.mock("prompts", () => ({ default: vi.fn() }));

beforeEach(() => {
  vi.stubEnv("CI", "false");
  vi.mocked(spawnAsync).mockResolvedValue({} as Awaited<ReturnType<typeof spawnAsync>>);
});

afterEach(() => {
  vi.resetAllMocks();
  vi.unstubAllEnvs();
});

test.each([
  { yes: true, ci: false },
  { yes: false, ci: true },
])(
  "skips Git initialization inside an existing repository without prompting (%j)",
  async ({ yes, ci }) => {
    vi.stubEnv("CI", String(ci));

    await expect(initGitRepoAsync("/app", { yes })).resolves.toBe(false);

    expect(prompts).not.toHaveBeenCalled();
    expect(vi.mocked(spawnAsync).mock.calls.map(([, args]) => args)).toEqual([
      ["--version"],
      ["rev-parse", "--is-inside-work-tree"],
    ]);
  },
);

test.each([true, undefined])(
  "defaults to skipping an existing repository (answer: %s)",
  async (answer) => {
    vi.mocked(prompts).mockResolvedValue({ answer });

    await expect(initGitRepoAsync("/app")).resolves.toBe(false);

    expect(prompts).toHaveBeenCalledWith(expect.objectContaining({ initial: true }));
    expect(spawnAsync).toHaveBeenCalledTimes(2);
  },
);

test("initializes and commits a standalone repository with the CLI's package metadata", async () => {
  vi.mocked(spawnAsync)
    .mockResolvedValueOnce({} as Awaited<ReturnType<typeof spawnAsync>>)
    .mockRejectedValueOnce(new Error("not a Git repository"));

  await expect(initGitRepoAsync("/app", { yes: true })).resolves.toBe(true);

  expect(prompts).not.toHaveBeenCalled();
  expect(spawnAsync).toHaveBeenCalledWith(
    "git",
    ["commit", "-m", `Initial commit\n\nGenerated by ${packageJSON.name} ${packageJSON.version}.`],
    { cwd: "/app", stdio: "ignore" },
  );
});

test("can still initialize a nested repository when explicitly requested", async () => {
  vi.mocked(prompts).mockResolvedValue({ answer: false });

  await expect(initGitRepoAsync("/app")).resolves.toBe(true);

  expect(spawnAsync).toHaveBeenCalledWith("git", ["init"], { cwd: "/app", stdio: "ignore" });
});
